/** English capital name for a country code, or '' when unknown. */
export function capitalOf(code: string | undefined | null): string {
  if (!code) return '';
  return CAPITALS[code.trim().toUpperCase()]?.[0] ?? '';
}

/** Arabic capital name for a country code, or '' when unknown. */
export function capitalArOf(code: string | undefined | null): string {
  if (!code) return '';
  return CAPITALS[code.trim().toUpperCase()]?.[1] ?? '';
}

